// Embeds src/db/migrations/*.sql into a TS module so serverless bundles never need filesystem access.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
const dir = new URL('../src/db/migrations/', import.meta.url);
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
const body = files.map((f) => `  { name: ${JSON.stringify(f)}, sql: ${JSON.stringify(readFileSync(new URL(f, dir), 'utf8'))} },`).join('\n');
writeFileSync(new URL('../src/db/migrations.generated.ts', import.meta.url), `// GENERATED by scripts/embed-migrations.mjs — do not edit\nexport const MIGRATIONS: { name: string; sql: string }[] = [\n${body}\n];\n`);
console.log('embedded', files.length, 'migration(s)');
